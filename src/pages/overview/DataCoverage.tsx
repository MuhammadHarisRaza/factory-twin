/**
 * Data freshness & coverage: the honest basis of every figure on the page — no plant system is connected,
 * what the signal catalogue has (simulated / not modelled / unavailable), how current the simulated signals
 * are now, and which asset feeds are stale. Detail: Events & Reports › Data & connectivity.
 */
import { ArrowRight, CircleCheck, CircleDashed, CircleHelp, CircleSlash, Clock, OctagonX, Radio, Unplug, type LucideIcon } from 'lucide-react';
import { openView } from '../../app/store';
import type { AvailabilityStatus } from '../../model/catalog';
import { useSimValue } from '../../sim/store';
import { formatClock } from '../../sim/time';
import { Section } from '../../ui/kit/Page';
import { StatusBadge, type Tone } from '../../ui/kit/Status';
import { dataCoverage } from './coverage';

const STATUS_STYLE: Record<AvailabilityStatus, { tone: Tone; icon: LucideIcon; hint: string }> = {
  simulated: { tone: 'warning', icon: CircleDashed, hint: 'Values generated by the demo simulation — not plant telemetry' },
  'not-modelled': { tone: 'neutral', icon: CircleHelp, hint: 'In the catalogue, but the simulation has no model for it: no value is shown' },
  unavailable: { tone: 'neutral', icon: CircleSlash, hint: 'Needs a system or sensor this demo does not have (e.g. energy meters, MES, QMS)' },
  reference: { tone: 'neutral', icon: CircleDashed, hint: 'Reference data, not a measurement' },
  connected: { tone: 'good', icon: Radio, hint: 'Delivered by a working connection' },
};

export function DataCoveragePanel() {
  const d = useSimValue((s) => dataCoverage(s));
  const f = d.freshness;
  const notCurrent = f.late + f.stale + f.bad + f.noValue;
  return (
    <Section
      className="ov-data"
      title="Data freshness & coverage"
      subtitle={`Signal catalogue and simulated feeds · ${formatClock(d.at)}`}
      actions={
        <button type="button" className="btn ghost sm" onClick={() => openView('events', 'data')} title="Sources, feeds and signal coverage by stage in Events & Reports">
          Data &amp; connectivity
          <ArrowRight size={12} aria-hidden />
        </button>
      }
    >
      <div className="ov-data-head">
        <StatusBadge tone={d.connected ? 'good' : 'neutral'} icon={d.connected ? Radio : Unplug} label={d.headline} />
        <span className="muted" title={`Not connected: ${d.sources.notConnected.join(', ')}`}>
          {d.sources.simulated.length} simulated source · {d.sources.notConnected.length} plant integrations not connected ({d.sources.notConnected.join(', ')})
        </span>
      </div>
      <div className="ov-data-g">
        <div>
          <h4 className="ov-data-t">
            Signal catalogue <span className="num muted">{d.catalogue.total}</span>
          </h4>
          <ul className="ov-data-l">
            {d.catalogue.rows.map((r) => {
              const st = STATUS_STYLE[r.status];
              return (
                <li key={r.status} title={st.hint}>
                  <StatusBadge tone={st.tone} icon={st.icon} label={r.label} />
                  <span className="ov-data-bar" aria-hidden>
                    <i style={{ width: `${Math.round(r.share * 100)}%` }} />
                  </span>
                  <b className="num">{r.count}</b>
                </li>
              );
            })}
          </ul>
        </div>
        <div>
          <h4 className="ov-data-t">
            Simulated signals now <span className="num muted">{f.checked}</span>
          </h4>
          <ul className="ov-data-l">
            <li title="Good or uncertain quality, updated within twice the expected interval">
              <StatusBadge tone="good" icon={CircleCheck} label="Current" />
              <b className="num">{f.current}</b>
            </li>
            {f.eventDriven > 0 && (
              <li title="Event-driven signals (gate events, sample results, alarms): reported when something happens, so their age is not judged">
                <StatusBadge tone="neutral" icon={CircleDashed} label="Event-driven" />
                <b className="num">{f.eventDriven}</b>
              </li>
            )}
            <li className={f.late + f.stale ? undefined : 'zero'} title="Last value older than twice (late) or five times (stale) the expected interval, or flagged stale — not current">
              <StatusBadge tone={f.late + f.stale ? 'warning' : 'neutral'} icon={Clock} label="Late or stale" />
              <b className="num">{f.late + f.stale}</b>
            </li>
            <li className={f.bad ? undefined : 'zero'} title="Flagged bad by the source: the values are not used">
              <StatusBadge tone={f.bad ? 'critical' : 'neutral'} icon={OctagonX} label="Flagged bad" />
              <b className="num">{f.bad}</b>
            </li>
            <li className={f.noValue ? undefined : 'zero'} title="No value delivered (never received, or missing samples)">
              <StatusBadge tone={f.noValue ? 'warning' : 'neutral'} icon={CircleSlash} label="No value" />
              <b className="num">{f.noValue}</b>
            </li>
          </ul>
        </div>
      </div>
      <p className="ov-data-feeds">
        {d.staleFeeds.length ? (
          <>
            <b>Feeds stale now:</b> {d.staleFeeds.map((x) => `${x.id} since ${x.clock}`).join(' · ')} — their states are unknown and their values frozen.
          </>
        ) : notCurrent ? (
          `No whole asset feed is stale; ${notCurrent} signal${notCurrent > 1 ? 's are' : ' is'} not current (see Data & connectivity).`
        ) : (
          'No asset feed is stale now.'
        )}
      </p>
    </Section>
  );
}

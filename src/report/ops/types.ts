/**
 * Operational report model — the ONE model behind the in-app report preview
 * (src/ui/report/OpsReportView.tsx) and the PDF export (./pdf.ts). Builders (shift.ts, oee.ts,
 * quality.ts, fleet.ts) read the shared simulation state through the same functions the workspaces
 * use (src/intel/kpis.ts, src/sim/metrics.ts, src/intel/report.ts eventImpact), so a report never
 * shows a figure the app computes differently, and the PDF never shows a figure the preview does not.
 *
 * Every section and table carries the kind of information it holds (`basis`), printed as a tag:
 * measured in the simulation, simulated, estimated, illustrative (see LEGEND).
 */
import type { KpiModel } from '../../intel/kpis';
import type { AlertSeverity, EventCategory, EventStatus, Evidence, MonitoredStageId } from '../../model/types';
import type { PeriodKey } from '../../sim/metrics';
import type { ReportEventQuery } from './select';

export type { ReportEventQuery } from './select';

/** The four operational report types (the fifth, the incident investigation, is the event report). */
export type OpsReportType = 'shift' | 'oee' | 'quality' | 'fleet';
export type ReportType = OpsReportType | 'incident';

/** Periods a report can cover: every period of the header selector (a completed shift included). */
export type ReportPeriodKey = PeriodKey;
export const REPORT_PERIODS: ReportPeriodKey[] = ['shift', 'prev-shift', 'today', '24h', '7d'];

/** Scope: the whole line (or site, for vehicles) or one monitored stage. */
export type ReportScope = 'line' | MonitoredStageId;

/** What kind of information a figure is. */
export type Basis = 'measured' | 'simulated' | 'estimated' | 'illustrative';

export const BASIS_LABEL: Record<Basis, string> = {
  measured: 'Measured in simulation',
  simulated: 'Simulated',
  estimated: 'Estimated',
  illustrative: 'Illustrative',
};

export const LEGEND: { basis: Basis; label: string; text: string }[] = [
  {
    basis: 'measured',
    label: BASIS_LABEL.measured,
    text: 'Counted at a modelled counting point or signal of the simulated plant (tiles accepted at sorting, kiln minutes, gate events) — measured the way a plant system would, but in a simulation, not a real plant.',
  },
  {
    basis: 'simulated',
    label: BASIS_LABEL.simulated,
    text: 'Generated by the simulation or by a demo scenario: events, equipment states, vehicle positions and inspection classifications.',
  },
  {
    basis: 'estimated',
    label: BASIS_LABEL.estimated,
    text: 'Derived from measured values with stated assumptions — output lost at the design rate, financial figures. Not verified results.',
  },
  {
    basis: 'illustrative',
    label: BASIS_LABEL.illustrative,
    text: 'Indicative only: digital-twin camera renders, inspection frames drawn for simulated records, price and cost assumptions.',
  },
];

export type ReportKpi = KpiModel & { basis: Basis };

/** One table cell: plain text, or text that links to an event / stage in the app (plain text in the PDF). */
export type ReportCell = string | { text: string; eventId?: string; stage?: MonitoredStageId; vehicleId?: string };

export const cellText = (c: ReportCell) => (typeof c === 'string' ? c : c.text);

export type ReportEvidenceItem = {
  eventId: string;
  evidenceId: string;
  kind: 'camera-snapshot' | 'inspection-image';
  title: string;
  /** Provenance and context lines printed under the image. */
  caption: string[];
  status: 'available' | 'pending' | 'unavailable';
  /** Why there is no image (when not available). */
  reason?: string;
  inspectionId?: string;
  /** Provenance of the evidence record: a camera snapshot is a digital-twin render or a frame of a configured camera stream. */
  provenance: Evidence['provenance'];
};

export type ReportChart = {
  title: string;
  /** The question the chart answers (shown above it). */
  question: string;
  unit: string;
  labels: string[];
  series: { label: string; values: (number | null)[]; dashed?: boolean }[];
  limit?: { label: string; value: number };
};

export type ReportBlock =
  | { kind: 'kpis'; items: ReportKpi[]; note?: string }
  | { kind: 'kv'; rows: [string, string][] }
  | {
      kind: 'table';
      head: string[];
      rows: ReportCell[][];
      align?: ('l' | 'r')[];
      widths?: (number | 'auto')[];
      empty?: string;
      foot?: string[];
      /** In-app preview only: show the first n rows and a "Show all" control (the PDF always prints every row). */
      collapseAfter?: number;
    }
  | { kind: 'bars'; title: string; unit: string; rows: { label: string; value: number; display: string; note?: string }[]; empty?: string }
  | { kind: 'chart'; chart: ReportChart }
  | { kind: 'text'; text: string; tone?: 'normal' | 'muted' }
  | { kind: 'list'; items: string[]; numbered?: boolean }
  | { kind: 'subhead'; text: string }
  | { kind: 'missing'; title: string; reason: string }
  | { kind: 'total'; label: string; value: string; note?: string }
  | { kind: 'evidence'; items: ReportEvidenceItem[] }
  /** In-app preview only: opens the Events tab listing exactly these events (nothing is printed in the PDF). */
  | { kind: 'events-link'; count: number; query: ReportEventQuery };

export type ReportSection = { id: string; title: string; basis?: Basis; tag?: string; blocks: ReportBlock[] };

export type ReportEventRow = {
  id: string;
  start: number;
  title: string;
  severity: AlertSeverity;
  status: EventStatus;
  category: EventCategory;
  active: boolean;
  source: 'simulation' | 'scenario';
  where: string;
  impact: string;
  estimate: number | null;
};

export type OpsReport = {
  type: OpsReportType;
  typeLabel: string;
  title: string;
  /** One data-driven sentence. */
  summary: string;
  period: { key: ReportPeriodKey; label: string; from: number; to: number; text: string };
  scope: { id: ReportScope; label: string };
  generatedAt: string;
  generatedAtPlant: string;
  /** Plant minute the model was built at. */
  minute: number;
  /** The headline KPIs exactly as src/intel/kpis.ts returns them for this period. */
  kpis: ReportKpi[];
  sections: ReportSection[];
  /** Significant events of the report (also rendered inside a section) — every one is listed, in the preview and the PDF. */
  events: ReportEventRow[];
  /** How `events` were selected; the Events tab reproduces the same list from it. */
  eventQuery: ReportEventQuery;
  legend: typeof LEGEND;
  fileName: string;
  disclaimer: string;
  /** Currency of the money figures. */
  currency: string;
};

export type OpsReportOptions = {
  period: ReportPeriodKey;
  scope?: ReportScope;
  finance?: import('../../sim/finance').FinanceAssumptions;
  tariffs?: import('../../sim/energy').Tariffs;
  generatedAt?: string;
};

/**
 * Shared page building blocks of the seven workspaces: page header, KPI card, section, tabs,
 * provenance badge, disclosure, side panel and empty / unavailable states. Pages compose these
 * instead of styling their own variants, so every workspace reads the same way:
 * title + context → one-sentence summary → a few KPIs → the primary work area → evidence → actions.
 */
import { useEffect, useId, useRef, useState, type KeyboardEvent as ReactKeyboardEvent, type ReactNode } from 'react';
import { ChevronDown, CircleCheck, CircleSlash, Clapperboard, CircleDashed, Clock, Inbox, OctagonAlert, Radio, TriangleAlert, X, type LucideIcon } from 'lucide-react';
import type { KpiModel } from '../../intel/kpis';
import { useApp, type NavMode, type WorkspaceId } from '../../app/store';
import type { Tone } from './Status';
import './kit.css';

// ── Provenance ──────────────────────────────────────────────────────────────

/**
 * Where a value, record or picture comes from. SIMULATED: generated by the demo or scenario engine ·
 * REFERENCE VIDEO: footage illustrating a process or equipment type · CONNECTED: a real
 * integration that is delivering (only a user-configured camera stream that is playing, in this
 * release) · STALE: was available, no longer fresh · UNAVAILABLE: cannot currently be accessed ·
 * ESTIMATE: derived with stated assumptions · ILLUSTRATIVE: indicative only (e.g. tariffs, prices) ·
 * SCENARIO: caused by a scenario the presenter started.
 */
export type Provenance = 'simulated' | 'reference' | 'recorded' | 'connected' | 'stale' | 'unavailable' | 'estimate' | 'illustrative' | 'scenario';

export const PROVENANCE: Record<Provenance, { label: string; icon: LucideIcon; title: string }> = {
  simulated: { label: 'Simulated', icon: CircleDashed, title: 'Generated by the demo simulation engine — not plant telemetry' },
  reference: { label: 'Reference video', icon: Clapperboard, title: 'Footage illustrating the process or equipment type — not this plant, not a live feed' },
  recorded: { label: 'Recorded footage', icon: Clapperboard, title: 'A camera recording provided by the client — not a live feed, and not linked to the simulated data of this demo' },
  connected: { label: 'Connected', icon: Radio, title: 'Delivered by a configured, working connection' },
  stale: { label: 'Stale', icon: Clock, title: 'Previously available; no fresh data' },
  unavailable: { label: 'Unavailable', icon: CircleSlash, title: 'This source or measurement cannot currently be accessed' },
  estimate: { label: 'Estimate', icon: CircleDashed, title: 'Derived from the data with stated assumptions' },
  illustrative: { label: 'Illustrative', icon: CircleDashed, title: 'Indicative assumption, not a measured value' },
  scenario: { label: 'Scenario', icon: CircleDashed, title: 'Caused by a scenario started in the simulation' },
};

/** Small uppercase provenance label (icon + text; never colour alone). */
export function ProvenanceBadge({ kind, title, className = '' }: { kind: Provenance; title?: string; className?: string }) {
  const p = PROVENANCE[kind];
  const Icon = p.icon;
  return (
    <span className={`prov prov-${kind} ${className}`} title={title ?? p.title}>
      <Icon size={11} strokeWidth={2.2} aria-hidden />
      {p.label}
    </span>
  );
}

// ── Page header ─────────────────────────────────────────────────────────────

/**
 * Page title, its context (scope · period · source) and the one-sentence operational summary.
 * `actions` sit on the right (primary path to act or investigate).
 */
export function PageHeader({
  title,
  context,
  summary,
  actions,
  provenance = 'simulated',
}: {
  title: ReactNode;
  /** Scope and period, e.g. "Tile line 1 · Shift B (06:00–14:00)". */
  context?: ReactNode;
  /** One concise, data-driven sentence answering the page's question. */
  summary?: ReactNode;
  actions?: ReactNode;
  provenance?: Provenance | null;
}) {
  return (
    <header className="pg-head">
      <div className="pg-head-main">
        <div className="pg-title-row">
          <h2 className="pg-title">{title}</h2>
          {provenance && <ProvenanceBadge kind={provenance} />}
        </div>
        {context && <div className="pg-context">{context}</div>}
        {summary && <p className="pg-summary">{summary}</p>}
      </div>
      {actions && <div className="pg-actions">{actions}</div>}
    </header>
  );
}

// ── KPI card ────────────────────────────────────────────────────────────────

export type KpiStatus = { tone: Tone; label: string; icon?: LucideIcon };

/**
 * One headline metric: plain-language name, large value + unit, its time scope, a target or
 * comparison, a short status (icon + words) and why it matters. `unavailable` replaces the value
 * with the reason it cannot be calculated — never a made-up number.
 */
export function KpiCard({
  label,
  value,
  unit,
  scope,
  target,
  status,
  why,
  unavailable,
  provenance,
  onClick,
  actionLabel,
  selected = false,
  textValue,
}: {
  label: string;
  value?: ReactNode;
  unit?: ReactNode;
  scope: ReactNode;
  target?: ReactNode;
  status?: KpiStatus | null;
  why?: ReactNode;
  unavailable?: string | null;
  provenance?: Provenance;
  onClick?: () => void;
  /** Accessible name of the click action, e.g. "Open OEE breakdown". */
  actionLabel?: string;
  selected?: boolean;
  /** The value is a word or name (e.g. a defect category), not a number: it wraps instead of being cut off. */
  textValue?: boolean;
}) {
  const body = (
    <>
      <div className="kc-top">
        <span className="kc-label">{label}</span>
        {provenance && provenance !== 'simulated' && <ProvenanceBadge kind={provenance} />}
      </div>
      {unavailable ? (
        <div className="kc-value kc-na" title={unavailable}>
          Unavailable
        </div>
      ) : (
        <div className={`kc-value ${textValue ? 'kc-text' : ''}`} title={textValue && typeof value === 'string' ? value : undefined}>
          <span className={textValue ? undefined : 'num'}>{value}</span>
          {unit && <small>{unit}</small>}
        </div>
      )}
      <div className="kc-scope">{scope}</div>
      {(target || status) && (
        <div className="kc-row">
          {status && <KpiStatusText status={status} />}
          {target && <span className="kc-target">{target}</span>}
        </div>
      )}
      {unavailable ? <div className="kc-why">{unavailable}</div> : why ? <div className="kc-why">{why}</div> : null}
    </>
  );
  const cls = `kc ${status ? `kc-${status.tone}` : ''} ${selected ? 'on' : ''}`;
  return onClick ? (
    // The visible content (name, value, unit, status, target) stays the accessible name; the action is appended.
    <button type="button" className={`${cls} kc-btn`} onClick={onClick} aria-pressed={selected || undefined}>
      {body}
      {actionLabel && <span className="sr-only"> — {actionLabel}</span>}
    </button>
  ) : (
    <div className={cls}>{body}</div>
  );
}

export function KpiStatusText({ status }: { status: KpiStatus }) {
  const Icon = status.icon;
  return (
    <span className={`kc-status ${status.tone}`}>
      {Icon ? <Icon size={12} strokeWidth={2.4} aria-hidden /> : <i className="kc-dot" aria-hidden />}
      {status.label}
    </span>
  );
}

const STATUS_ICON: Partial<Record<Tone, LucideIcon>> = { good: CircleCheck, warning: TriangleAlert, serious: TriangleAlert, critical: OctagonAlert, neutral: Clock };

/** A shared KPI (src/intel/kpis.ts) as KpiCard props — every page renders the same name, value, scope, status and provenance. */
export function kpiCardProps(k: KpiModel) {
  return {
    label: k.label,
    value: k.display,
    unit: k.unit,
    scope: k.scope,
    target: k.target,
    status: k.status ? ({ tone: k.status.tone, label: k.status.label, icon: STATUS_ICON[k.status.tone] } satisfies KpiStatus) : null,
    why: k.why,
    unavailable: k.unavailable ?? null,
    provenance: k.provenance,
    textValue: k.value != null && !/^[\d.,\s%+\-−]+$/.test(k.display),
  };
}

/** A row of at most five KPI cards. */
export function KpiRow({ children, label }: { children: ReactNode; label: string }) {
  return (
    <div className="kc-row-grid" role="group" aria-label={label}>
      {children}
    </div>
  );
}

// ── Section ─────────────────────────────────────────────────────────────────

/** A titled block of a page (lighter than a panel: no heavy chrome, optional actions). */
export function Section({
  title,
  subtitle,
  actions,
  children,
  className = '',
  id,
  flush = false,
}: {
  title?: ReactNode;
  subtitle?: ReactNode;
  actions?: ReactNode;
  children: ReactNode;
  className?: string;
  id?: string;
  /** No body padding (lists and tables that run to the edge). */
  flush?: boolean;
}) {
  return (
    <section className={`sec ${className}`} id={id}>
      {(title || actions) && (
        <header className="sec-h">
          <div className="sec-titles">
            {title && <h3>{title}</h3>}
            {subtitle && <p>{subtitle}</p>}
          </div>
          {actions && <div className="sec-actions">{actions}</div>}
        </header>
      )}
      <div className={`sec-b ${flush ? 'flush' : ''}`}>{children}</div>
    </section>
  );
}

// ── Tabs (route-bound) ──────────────────────────────────────────────────────

/**
 * The sub-view of a workspace, kept in the address (?tab=…) so Back / Forward and links restore it.
 * Returns the current tab (or `fallback`) and a setter.
 */
export function useWorkspaceTab<T extends string>(ws: WorkspaceId, fallback: T, allowed: readonly T[]): [T, (t: T, mode?: NavMode) => void] {
  const raw = useApp((s) => s.tabs[ws]);
  const tab = raw && (allowed as readonly string[]).includes(raw) ? (raw as T) : fallback;
  const set = (t: T, mode: NavMode = 'push') => useApp.getState().setTab(ws, t === fallback ? null : t, mode);
  return [tab, set];
}

export function Tabs<T extends string>({
  value,
  options,
  onChange,
  label,
}: {
  value: T;
  options: { value: T; label: ReactNode; count?: number | null; title?: string }[];
  onChange: (v: T) => void;
  label: string;
}) {
  const ref = useRef<HTMLDivElement>(null);
  const onKey = (e: ReactKeyboardEvent) => {
    if (e.key !== 'ArrowRight' && e.key !== 'ArrowLeft') return;
    const i = options.findIndex((o) => o.value === value);
    const next = options[(i + (e.key === 'ArrowRight' ? 1 : -1) + options.length) % options.length];
    onChange(next.value);
    requestAnimationFrame(() => ref.current?.querySelector<HTMLButtonElement>('[aria-selected="true"]')?.focus());
    e.preventDefault();
  };
  return (
    <div className="tabs" role="tablist" aria-label={label} ref={ref} onKeyDown={onKey}>
      {options.map((o) => (
        <button
          key={o.value}
          type="button"
          role="tab"
          aria-selected={o.value === value}
          tabIndex={o.value === value ? 0 : -1}
          className={o.value === value ? 'on' : ''}
          onClick={() => {
            onChange(o.value);
            // A tab switch lower down the page brings the tab bar back into view (the new view starts below it).
            requestAnimationFrame(() => {
              const el = ref.current;
              const box = el?.closest('.content') as HTMLElement | null;
              if (el && box && el.getBoundingClientRect().top < box.getBoundingClientRect().top) el.scrollIntoView({ block: 'start' });
            });
          }}
          title={o.title}
        >
          {o.label}
          {o.count != null && <span className="tabs-count num">{o.count}</span>}
        </button>
      ))}
    </div>
  );
}

// ── Disclosure ──────────────────────────────────────────────────────────────

/** A collapsed section for secondary detail (technical data, method, raw records). */
export function Disclosure({ title, children, defaultOpen = false, meta }: { title: ReactNode; children: ReactNode; defaultOpen?: boolean; meta?: ReactNode }) {
  const [open, setOpen] = useState(defaultOpen);
  const id = useId();
  return (
    <div className={`disc ${open ? 'open' : ''}`}>
      <button type="button" className="disc-h" aria-expanded={open} aria-controls={id} onClick={() => setOpen(!open)}>
        <ChevronDown size={14} className="disc-chev" aria-hidden />
        <span className="disc-title">{title}</span>
        {meta && <span className="disc-meta">{meta}</span>}
      </button>
      {open && (
        <div className="disc-b" id={id}>
          {children}
        </div>
      )}
    </div>
  );
}

// ── Side panel ──────────────────────────────────────────────────────────────

/** A contextual detail panel docked to the right of a work area (closes with its button or Esc). */
export function SidePanel({ title, subtitle, onClose, children, footer, className = '' }: { title: ReactNode; subtitle?: ReactNode; onClose?: () => void; children: ReactNode; footer?: ReactNode; className?: string }) {
  // One listener for the panel's lifetime (onClose is often a new function on every simulated tick; re-adding
  // the listener would change its order relative to drawers). The latest onClose is read from a ref.
  const closeRef = useRef(onClose);
  closeRef.current = onClose;
  const closable = !!onClose;
  useEffect(() => {
    if (!closable) return;
    const onKey = (e: KeyboardEvent) => {
      // A modal drawer or dialog (Scenarios, Copilot, snapshot viewer) handles its own Esc (default-prevented).
      if (e.key !== 'Escape' || e.defaultPrevented) return;
      if (document.querySelector('[aria-modal="true"]')) return;
      const t = e.target as HTMLElement | null;
      if (t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA' || t.tagName === 'SELECT')) return;
      if (t && !t.isConnected) return; // the key started in something that has just closed
      closeRef.current?.();
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [closable]);
  return (
    <aside className={`sp ${className}`} aria-label={typeof title === 'string' ? title : undefined}>
      <header className="sp-h">
        <div className="sp-titles">
          <h3>{title}</h3>
          {subtitle && <div className="sp-sub">{subtitle}</div>}
        </div>
        {onClose && (
          <button type="button" className="btn ghost sm icon" onClick={onClose} aria-label="Close panel" title="Close (Esc)">
            <X size={15} />
          </button>
        )}
      </header>
      <div className="sp-b">{children}</div>
      {footer && <footer className="sp-f">{footer}</footer>}
    </aside>
  );
}

// ── Empty / unavailable states ──────────────────────────────────────────────

/** Nothing to show — says why and, when useful, what to do. */
export function EmptyState({ title, children, icon: Icon = Inbox, action }: { title: string; children?: ReactNode; icon?: LucideIcon; action?: ReactNode }) {
  return (
    <div className="es" role="status">
      <Icon size={20} aria-hidden />
      <b>{title}</b>
      {children && <div className="es-text">{children}</div>}
      {action}
    </div>
  );
}

/** A metric or parameter the data does not contain: says so instead of showing a plausible value. */
export function Unavailable({ reason, children = 'Unavailable' }: { reason: string; children?: ReactNode }) {
  return (
    <span className="na" title={reason}>
      {children}
    </span>
  );
}

/** Compact label/value list for detail panels (value may be <Unavailable/>). */
export function Facts({ rows }: { rows: { label: ReactNode; value: ReactNode; hint?: string }[] }) {
  return (
    <dl className="facts">
      {rows.map((r, i) => (
        <div key={i} title={r.hint}>
          <dt>{r.label}</dt>
          <dd>{r.value}</dd>
        </div>
      ))}
    </dl>
  );
}
